using System.Globalization;
using System.Text;

namespace Wolfgang.Barefoot.Core.Hosting;

/// <summary>
/// The catalogue of exit codes: what each means, which binary uses it, and whether the scheduled job
/// stops on it (ADR 0007, ADR 0018). <c>docs/EXIT-CODES.md</c> is <see cref="ToMarkdown"/> written to a file.
/// </summary>
public static class ExitCodes
{
    private const string Scraper = "bf-scraper";

    private const string Admin = "bf";

    private const string Maintenance = "bf-maint";

    private static readonly string[] Every = [Scraper, Admin, Maintenance];

    private static readonly string[] ApiClients = [Scraper, Admin];



    /// <summary>
    /// Every exit code, in numeric order.
    /// </summary>
    public static IReadOnlyList<ExitCodeInfo> All { get; } =
    [
        new(ExitCode.Ok, "Done.", Every, StopsTheJob: false),
        new(ExitCode.Failed, "The verb failed: a migration failed, or an exception nothing handled.", Every, StopsTheJob: false),
        new(ExitCode.Partial, "Finished with warnings; some items did not complete.", ApiClients, StopsTheJob: false),
        new(ExitCode.BreakerTripped, "The scraper stopped the run because the site was unhappy; resume later.", [Scraper], StopsTheJob: false),
        new(ExitCode.Usage, "Bad arguments or configuration.", Every, StopsTheJob: false),
        new(ExitCode.VersionMismatch, "The API is too old or too new for this binary; the message says which side to update.", ApiClients, StopsTheJob: true),
        new(ExitCode.DataLossNotConfirmed, "A downgrade would lose data and `--confirm-data-loss` was not given.", [Maintenance], StopsTheJob: false),
        new(ExitCode.ApiUnavailable, "The API could not be reached within the retry budget.", ApiClients, StopsTheJob: true),
        new(ExitCode.DatabaseUnavailable, "The database could not be reached within the retry budget.", Every, StopsTheJob: true),
        new(ExitCode.QuotaExhausted, "The monthly free database allowance is used up.", Every, StopsTheJob: true),
        new(ExitCode.Refused, "The tool will not act: the database is newer than this build, or the API refused a catalog snapshot.", Every, StopsTheJob: true),
        new(ExitCode.MissingMigration, "The database is behind this build: a migration is not applied. Run `bf-maint migrate`.", Every, StopsTheJob: true),
    ];



    /// <summary>
    /// What <paramref name="code"/> means.
    /// </summary>
    /// <param name="code">A defined exit code.</param>
    /// <exception cref="ArgumentOutOfRangeException"><paramref name="code"/> is not a defined exit code.</exception>
    public static ExitCodeInfo Describe(ExitCode code)
    {
        return All.FirstOrDefault(info => info.Code == code)
            ?? throw new ArgumentOutOfRangeException(nameof(code), code, "Not a defined exit code.");
    }



    /// <summary>
    /// The exit-code reference as Markdown: the content of <c>docs/EXIT-CODES.md</c>. Lines end in a
    /// line feed and the text does not depend on the machine's culture.
    /// </summary>
    public static string ToMarkdown()
    {
        var text = new StringBuilder();

        text.Append("# Exit codes\n\n");
        text.Append("Generated from `ExitCode` and `ExitCodes` in `Wolfgang.Barefoot.Core`. Do not edit this file by hand;\n");
        text.Append("change the code and run `scripts/Update-GeneratedDocs.ps1`. A test fails when the two differ.\n\n");
        text.Append("The three command-line tools share one numbering (ADR 0007), so a code never means two things.\n\n");
        text.Append("| Code | Name | Meaning | Used by | The scheduled job |\n");
        text.Append("|---|---|---|---|---|\n");

        foreach (var info in All)
        {
            text.Append
            (
                CultureInfo.InvariantCulture,
                $"| {(int)info.Code} | `{info.Code}` | {info.Meaning} | {string.Join(", ", info.UsedBy.Select(name => $"`{name}`"))} | {(info.StopsTheJob ? "stops" : "continues")} |\n"
            );
        }

        text.Append("\nThe scheduled job runs its steps in order and reads each step's exit code. It stops on a code\n");
        text.Append("marked *stops*, because no later step can work, and goes on to the next step otherwise: after a\n");
        text.Append("partial run or a tripped breaker the digests for what did complete are still sent.\n");

        return text.ToString();
    }
}
