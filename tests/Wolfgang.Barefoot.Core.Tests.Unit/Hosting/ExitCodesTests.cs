using Wolfgang.Barefoot.Core.Hosting;

namespace Wolfgang.Barefoot.Core.Tests.Unit.Hosting;

public sealed class ExitCodesTests
{
    [Theory]
    [InlineData(ExitCode.Ok, 0)]
    [InlineData(ExitCode.Failed, 1)]
    [InlineData(ExitCode.Partial, 2)]
    [InlineData(ExitCode.BreakerTripped, 3)]
    [InlineData(ExitCode.Usage, 4)]
    [InlineData(ExitCode.VersionMismatch, 5)]
    [InlineData(ExitCode.DataLossNotConfirmed, 6)]
    [InlineData(ExitCode.ApiUnavailable, 7)]
    [InlineData(ExitCode.DatabaseUnavailable, 8)]
    [InlineData(ExitCode.QuotaExhausted, 9)]
    [InlineData(ExitCode.Refused, 10)]
    [InlineData(ExitCode.MissingMigration, 11)]
    public void ExitCode_when_cast_to_a_number_has_the_value_ADR_0007_gives_it(ExitCode code, int expected)
    {
        Assert.Equal(expected, (int)code);
    }



    [Fact]
    public void All_when_read_describes_every_code_once_in_numeric_order()
    {
        var described = ExitCodes
            .All
            .Select(info => info.Code)
            .ToList();

        Assert.Equal(Enum.GetValues<ExitCode>().Order(), described);
    }



    [Fact]
    public void All_when_read_gives_every_code_a_meaning_and_a_known_user()
    {
        Assert.All
        (
            ExitCodes.All,
            info =>
            {
                Assert.False(string.IsNullOrWhiteSpace(info.Meaning));
                Assert.NotEmpty(info.UsedBy);
                Assert.All(info.UsedBy, name => Assert.Contains(name, new[] { "bf-scraper", "bf", "bf-maint" }));
            }
        );
    }



    [Fact]
    public void All_when_read_marks_exactly_the_six_codes_the_job_stops_on()
    {
        var stops = ExitCodes
            .All
            .Where(info => info.StopsTheJob)
            .Select(info => (int)info.Code);

        Assert.Equal([5, 7, 8, 9, 10, 11], stops);
    }



    [Theory]
    [InlineData(ExitCode.BreakerTripped, "bf-scraper")]
    [InlineData(ExitCode.DataLossNotConfirmed, "bf-maint")]
    public void Describe_when_a_code_belongs_to_one_binary_names_only_that_binary(ExitCode code, string binary)
    {
        Assert.Equal([binary], ExitCodes.Describe(code).UsedBy);
    }



    [Theory]
    [InlineData(ExitCode.Partial)]
    [InlineData(ExitCode.VersionMismatch)]
    [InlineData(ExitCode.ApiUnavailable)]
    public void Describe_when_a_code_needs_the_API_names_the_two_API_clients(ExitCode code)
    {
        Assert.Equal(["bf-scraper", "bf"], ExitCodes.Describe(code).UsedBy);
    }



    [Theory]
    [InlineData(ExitCode.Ok)]
    [InlineData(ExitCode.Failed)]
    [InlineData(ExitCode.Usage)]
    [InlineData(ExitCode.DatabaseUnavailable)]
    [InlineData(ExitCode.QuotaExhausted)]
    [InlineData(ExitCode.Refused)]
    [InlineData(ExitCode.MissingMigration)]
    public void Describe_when_a_code_is_shared_names_all_three_binaries(ExitCode code)
    {
        Assert.Equal(["bf-scraper", "bf", "bf-maint"], ExitCodes.Describe(code).UsedBy);
    }



    [Theory]
    [InlineData(-1)]
    [InlineData(12)]
    public void Describe_when_the_code_is_not_defined_throws(int value)
    {
        var exception = Assert.Throws<ArgumentOutOfRangeException>(() => ExitCodes.Describe((ExitCode)value));

        Assert.Equal("code", exception.ParamName);
        Assert.Contains("Not a defined exit code", exception.Message, StringComparison.Ordinal);
    }



    [Fact]
    public void ToMarkdown_when_called_writes_one_table_row_per_code_with_line_feeds_only()
    {
        var markdown = ExitCodes.ToMarkdown();
        var rows = markdown
            .Split('\n')
            .Where(line => line.StartsWith("| ", StringComparison.Ordinal) && char.IsAsciiDigit(line[2]))
            .ToList();

        Assert.StartsWith("# Exit codes\n", markdown, StringComparison.Ordinal);
        Assert.EndsWith(".\n", markdown, StringComparison.Ordinal);
        Assert.DoesNotContain('\r', markdown);
        Assert.Equal(12, rows.Count);
        Assert.Contains("Generated from `ExitCode` and `ExitCodes` in `Wolfgang.Barefoot.Core`. Do not edit this file by hand;\n", markdown, StringComparison.Ordinal);
        Assert.Contains("change the code and run `scripts/Update-GeneratedDocs.ps1`. A test fails when the two differ.\n\n", markdown, StringComparison.Ordinal);
        Assert.Contains("The three command-line tools share one numbering (ADR 0007), so a code never means two things.\n\n", markdown, StringComparison.Ordinal);
        Assert.Contains("| Code | Name | Meaning | Used by | The scheduled job |\n|---|---|---|---|---|\n| 0 |", markdown, StringComparison.Ordinal);
        Assert.Contains("| stops |\n\nThe scheduled job runs its steps in order and reads each step's exit code. It stops on a code\n", markdown, StringComparison.Ordinal);
        Assert.Contains("marked *stops*, because no later step can work, and goes on to the next step otherwise: after a\n", markdown, StringComparison.Ordinal);
        Assert.EndsWith("partial run or a tripped breaker the digests for what did complete are still sent.\n", markdown, StringComparison.Ordinal);
        Assert.Equal("| 0 | `Ok` | Done. | `bf-scraper`, `bf`, `bf-maint` | continues |", rows[0]);
        Assert.Equal
        (
            "| 5 | `VersionMismatch` | The API is too old or too new for this binary; the message says which side to update. | `bf-scraper`, `bf` | stops |",
            rows[5]
        );
        Assert.Equal
        (
            "| 10 | `Refused` | The tool will not act: the database is newer than this build, or the API refused a catalog snapshot. | `bf-scraper`, `bf`, `bf-maint` | stops |",
            rows[10]
        );
        Assert.Equal
        (
            "| 11 | `MissingMigration` | The database is behind this build: a migration is not applied. Run `bf-maint migrate`. | `bf-scraper`, `bf`, `bf-maint` | stops |",
            rows[11]
        );
    }
}
